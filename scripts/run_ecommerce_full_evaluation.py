def badcases(report):
    rows = []
    for section_name, section in report.get("sections", {}).items():
        for failure in section.get("failures", [])[:20] if isinstance(section, dict) else []:
            rows.append({"section": section_name, "failure": failure})
    # Add observed diagnosis caveat as a quality badcase aggregate, because pass/fail hides it.
    diag = report["sections"].get("diagnosis_evidence_governance", {})
    q = (((diag.get("metrics") or {}).get("quality") or {}))
    if q.get("critical_hallucination_count"):
        rows.append({"section": "diagnosis_evidence_governance", "failure_category": "critical_hallucination_risk_observed", "count": q.get("critical_hallucination_count")})
    return rows[:10]


def resume_ready(report):
    e2e = report["sections"].get("e2e_sql_business_quality", {})
    rag = report["sections"].get("rag_retrieval_grounding", {})
    multi = report["sections"].get("multiturn_context", {})
    prod = report["sections"].get("production_control_plane_governance", {})
    durable = (prod.get("metrics") or {})
    out = []
    if e2e.get("status") == "measured":
        m = e2e.get("metrics", {})
        n = (e2e.get("sample_size") or {}).get("case_count")
        out.append("本地 SQLite 沙箱 %s 条电商 SQL/E2E 规则评测 overall_pass_rate=%.1f%%，SQL execution_success=%.1f%%；不含真实 LLM。" % (n, 100*m.get("overall_pass_rate", 0), 100*m.get("execution_success_rate", 0)))
    best = rag.get("selected_threshold_metrics") or {}
    ds = rag.get("sample_size") or {}
    if best:
        out.append("本地确定性 RAG 阈值评测 n=%s：Recall@5=%.1f%%，无答案拒答召回=%.1f%%，citation_accuracy=%.1f%%；不代表线上 embedding。" % (ds.get("case_count"), 100*best.get("recall@5", 0), 100*best.get("no_answer_recall", 0), 100*best.get("citation_accuracy", 0)))
    mm = multi.get("metrics") or {}
    if mm:
        out.append("多轮压力集 %s session / %s turns：安全终态/上下文压力 harness pass_rate=%.1f%%；需避免表述为真实运营成功率。" % ((multi.get("sample_size") or {}).get("session_count"), (multi.get("sample_size") or {}).get("turn_count"), 100*mm.get("pass_rate", 0)))
    if durable:
        out.append("生产控制面离线夹具 n=%s：duplicate_side_effect_count=%s、acl_leakage_count=%s、scope_leakage_count=%s。" % ((prod.get("sample_size") or {}).get("case_count"), durable.get("duplicate_side_effect_count"), durable.get("acl_leakage_count"), durable.get("scope_leakage_count")))
    return out


def markdown(report):
    lines = []
    meta = report["run_metadata"]
    lines.append("# Ecommerce Data Agent Full Evaluation Report")
    lines.append("")
    lines.append("## 1. Run Metadata")
    lines.append("")
    for key in ["run_id", "git_commit", "git_branch", "python_version", "os", "cpu", "memory_gb", "model_provider", "model_name", "embedding_model", "reranker_model", "database"]:
        lines.append("- `%s`: `%s`" % (key, meta.get(key)))
    lines.append("")
    lines.append("> 说明：本报告只汇总当前仓库可复现的本地/离线测评；未运行或环境不满足的项目标为 not_applicable/blocked，未伪造成已完成指标。")
    lines.append("")
    lines.append("## 2. Dataset Inventory")
    lines.append("")
    for name, item in sorted(report["dataset_inventory"].items()):
        lines.append("- `%s`: n=%s, exists=%s" % (name, item["case_count"], item["exists"]))
    lines.append("")
    lines.append("## 3. Measured Sections")
    for name, section in sorted(report["sections"].items()):
        lines.append("")
        lines.append("### %s" % name)
        lines.append("")
        lines.append("- status: `%s`" % section.get("status"))
        if section.get("report_path"):
            lines.append("- report: `%s`" % section.get("report_path"))
        if section.get("sample_size"):
            lines.append("- sample_size: `%s`" % json.dumps(section.get("sample_size"), ensure_ascii=False, sort_keys=True))
        if section.get("metrics"):
            lines.append("- metrics: `%s`" % json.dumps(section.get("metrics"), ensure_ascii=False, sort_keys=True)[:1500])
        if section.get("selected_threshold_metrics"):
            best = dict(section.get("selected_threshold_metrics"))
            best.pop("sample_rows", None)
            lines.append("- selected_threshold_metrics: `%s`" % json.dumps(best, ensure_ascii=False, sort_keys=True))
        if section.get("confidence_intervals_95"):
            lines.append("- confidence_intervals_95: `%s`" % json.dumps(section.get("confidence_intervals_95"), ensure_ascii=False, sort_keys=True))
        if section.get("limitations"):
            lines.append("- limitations: %s" % "; ".join(section.get("limitations")))
        if section.get("reason"):
            lines.append("- reason: %s" % section.get("reason"))
        if section.get("caveat"):
            lines.append("- caveat: %s" % section.get("caveat"))
        if section.get("important_caveat"):
            lines.append("- important_caveat: %s" % section.get("important_caveat"))
        for nested_name in ["intent", "agent_execution", "sql", "rag", "latency", "memory_multiturn", "tool_resilience", "simulated_load", "intent_router_eval", "rag_generation_eval", "safety_eval", "streaming_latency_eval"]:
            if section.get(nested_name):
                compact = section.get(nested_name)
                if isinstance(compact, dict) and compact.get("metrics"):
                    compact = compact.get("metrics")
                lines.append("- %s: `%s`" % (nested_name, json.dumps(compact, ensure_ascii=False, sort_keys=True)[:1500]))
        if section.get("environment_blocked_real_tests"):
            lines.append("- environment_blocked_real_tests: `%s`" % json.dumps(section.get("environment_blocked_real_tests"), ensure_ascii=False, sort_keys=True))
    lines.append("")
    lines.append("## 4. Top Bad Cases / Caveats")
