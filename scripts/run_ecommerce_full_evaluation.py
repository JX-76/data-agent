"""Aggregate the reproducible ecommerce Data Agent evaluation results.

This script intentionally does not modify business logic. It collects the local
harness/gate reports that are already generated by dedicated runners, records
run metadata, computes confidence intervals for available proportions, and marks
missing/non-comparable measurements as not_applicable instead of fabricating
numbers.
"""
