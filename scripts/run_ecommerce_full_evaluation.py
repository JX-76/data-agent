def ensure_dir(path):
    if not os.path.isdir(path):
        os.makedirs(path)


def read_json(path):
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def write_json(path, data):
    ensure_dir(os.path.dirname(path))
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(data, handle, ensure_ascii=False, indent=2, sort_keys=True)


def write_text(path, text):
    ensure_dir(os.path.dirname(path))
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


def count_jsonl(path):
    if not os.path.exists(path):
        return 0
    count = 0
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                count += 1
    return count


def ci95(success, total):
    if not total:
        return [0.0, 0.0]
    p = float(success) / float(total)
    z = 1.96
    denom = 1.0 + z * z / total
    centre = p + z * z / (2 * total)
    margin = z * math.sqrt((p * (1 - p) + z * z / (4 * total)) / total)
    return [round(max(0.0, (centre - margin) / denom), 4), round(min(1.0, (centre + margin) / denom), 4)]


def git(args):
    try:
        out = subprocess.check_output(["git", "-C", ROOT] + args, stderr=subprocess.STDOUT)
        return out.decode("utf-8", "replace").strip()
    except Exception as exc:
        return "unavailable: %s" % exc


def machine_metadata(run_id):
    memory_gb = None
    try:
        import psutil  # noqa
        memory_gb = round(psutil.virtual_memory().total / (1024.0 ** 3), 2)
    except Exception:
        memory_gb = None
    return {
        "run_id": run_id,
        "git_commit": git(["rev-parse", "HEAD"]),
        "git_branch": git(["branch", "--show-current"]),
        "git_status_short": git(["status", "--short"]),
        "python_version": sys.version.replace("\n", " "),
        "os": platform.platform(),
        "cpu": platform.processor() or platform.machine(),
        "memory_gb": memory_gb,
        "gpu": "not_detected_by_this_runner",
        "model_provider": os.environ.get("DATA_AGENT_MODEL_PROVIDER", "offline/local unless individual report states otherwise"),
        "model_name": os.environ.get("DATA_AGENT_MODEL_NAME", "not_applicable_for_no_llm_runs"),
        "embedding_model": os.environ.get("RAG_BGE_MODEL", "deterministic/local or cached BGE if benchmark executed"),
        "reranker_model": os.environ.get("RAG_BENCHMARK_RERANKER", "lexical/none"),
        "database": "SQLite fixture + local sandbox data; see per-report manifests",
        "concurrency": "see performance section; current aggregate is mostly offline deterministic",
        "warmup_runs": "not_applicable_unless_perf_report_present",
        "measured_runs": "see each dataset/report",
        "dataset_version": "local harness cases as of git commit",
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
    }


